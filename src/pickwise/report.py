"""Render the daily pick as Markdown and refresh the live sections of the README."""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

from .models import Pick
from .universe import sector_of

DISCLAIMER = (
    "> **Not financial advice.** Pickwise is an educational research project. Picks are "
    "generated automatically by an AI model, may be wrong, and do not account for your "
    "circumstances. Do your own research."
)
CONVICTION_BADGE = {"low": "🟡 Low", "medium": "🟠 Medium", "high": "🟢 High"}


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items) or "- _None noted._"


def render_pick(pick: Pick, as_of: str, price: float, candidates: pd.DataFrame, model: str) -> str:
    row = candidates.loc[pick.ticker]
    urls = [u for u in pick.sources if u.startswith(("http://", "https://"))]
    sources = "\n".join(f"- <{url}>" for url in urls) or "- _Market and fundamental data only._"
    shortlist = ", ".join(
        f"**{t}**" if t == pick.ticker else t for t in candidates.index
    )
    return f"""# {pick.ticker} · {pick.company}

**{as_of}** · {sector_of(pick.ticker)} · Conviction: {CONVICTION_BADGE[pick.conviction]} · \
Horizon: {pick.horizon}

> {pick.headline}

| Reference price | 3M return | 12-1M momentum | From 52W high | RSI (14) | Screen score |
|---|---|---|---|---|---|
| ${price:,.2f} | {row['return_3m']:+.1%} | {row['momentum_12_1']:+.1%} | \
{row['pct_from_high']:+.1%} | {row['rsi_14']:.0f} | {row['score']:.2f} |

## Thesis
{_bullets(pick.thesis)}

## Catalysts to watch
{_bullets(pick.catalysts)}

## Risks
{_bullets(pick.risks)}

## Why {pick.ticker} over {pick.runner_up}
{pick.why_not_runner_up}

## Sources
{sources}

<sub>Shortlist: {shortlist} · Generated by `{model}`</sub>

{DISCLAIMER}
"""


def render_track_record(perf: pd.DataFrame, stats: dict, limit: int = 10) -> str:
    if perf.empty:
        return "_Track record starts after the first pick._"
    if stats["picks"] == 0:
        headline = "_Stats start once the first pick has a full trading day behind it._"
    else:
        plural = "s" if stats["picks"] != 1 else ""
        headline = (
            f"**{stats['picks']} pick{plural}** · Hit rate **{stats['hit_rate']:.0%}** · "
            f"Beat S&P 500 **{stats['beat_benchmark_rate']:.0%}** · "
            f"Avg return **{stats['avg_return']:+.2%}** · "
            f"Avg alpha **{stats['avg_alpha']:+.2%}**"
        )
    lines = [
        headline,
        "",
        "| Date | Ticker | Conviction | Entry | Now | Return | vs S&P 500 |",
        "|---|---|---|---|---|---|---|",
    ]
    for _, r in perf.head(limit).iterrows():
        lines.append(
            f"| {r['date']} | [{r['ticker']}](picks/{r['date']}.md) | {r['conviction']} | "
            f"${r['entry']:,.2f} | ${r['current']:,.2f} | {r['return']:+.2%} | {r['alpha']:+.2%} |"
        )
    return "\n".join(lines)


def replace_section(text: str, name: str, body: str) -> str:
    """Swap the content between <!-- name:start --> and <!-- name:end --> markers."""
    pattern = re.compile(rf"(<!-- {name}:start -->\n).*?(\n<!-- {name}:end -->)", re.DOTALL)
    if not pattern.search(text):
        raise ValueError(f"README is missing the '{name}' markers.")
    return pattern.sub(lambda m: m.group(1) + body + m.group(2), text)


def update_readme(readme: Path, track_record_md: str, pick: Pick, as_of: str) -> None:
    text = readme.read_text()
    teaser = (
        f"### {as_of}: [{pick.ticker}](picks/{as_of}.md) · {pick.company}\n\n"
        f"> {pick.headline}\n\n"
        f"Conviction: {CONVICTION_BADGE[pick.conviction]} · Horizon: {pick.horizon} · "
        f"[Full write-up →](picks/{as_of}.md)"
    )
    text = replace_section(text, "today", teaser)
    text = replace_section(text, "track-record", track_record_md)
    readme.write_text(text)
